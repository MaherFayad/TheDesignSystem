import { chromium } from '/home/user/TheDesignSystem/node_modules/@playwright/test/index.mjs';
const [base, rtl] = process.argv.slice(2);
const q = rtl === 'rtl' ? '&style=desk&dir=rtl&lang=ar' : '&style=desk';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1280, height: 800 } })).newPage();
const log = []; const L = (...a) => log.push(a.join(' '));
const tick = () => p.evaluate(() => new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(() => setTimeout(r, 30)))));
const go = async (c) => { await p.goto(`${base}/c/${c}?chrome=0${q}`); await p.waitForSelector('[data-demo-case]', { state: 'attached' }); await p.waitForTimeout(500); };
const active = () => p.evaluate(() => { const a = document.activeElement; return `${a.tagName.toLowerCase()} part=${a.getAttribute('data-part')} name=${a.getAttribute('aria-label')}`; });
const press = async (k) => { await p.keyboard.press(k); await tick(); };
await go('search-field');
await p.$eval('[data-ds=search-field]:not([data-disabled]):not([data-readonly])', (e) => e.setAttribute('data-qa', ''));
const I = '[data-qa] input';
const v = () => p.$eval(I, (e) => `value=${JSON.stringify(e.value)} empty=${e.closest('[data-qa]').hasAttribute('data-empty')} clear=${!!e.closest('[data-qa]').querySelector('[data-part=clear]')}`);
await p.click(I); await p.keyboard.press('End'); await p.keyboard.type('abc'); await tick();
L('typed', await v(), await active());
await press('Escape'); L('Escape 1', await v(), await active());
await press('Escape'); L('Escape 2', await v(), await active());
await p.keyboard.type('xy'); await tick(); L('typed', await v());
await press('Tab'); L('Tab', await active());
await press('Enter'); L('Enter on clear', await v(), await active());
await p.keyboard.type('q'); await tick(); await press('Tab'); await press(' '); L('Space on clear', await v(), await active());
await p.keyboard.type('m'); await tick(); await p.click('[data-qa] [data-part=clear]'); await tick(); L('click clear', await v(), await active());
await p.keyboard.type('m'); await tick(); await press('Shift+Tab'); await press('Tab'); L('Tab back in', await v(), await active());
await press('Escape'); L('Escape after Tab back', await v(), await active());

await go('password-field');
await p.$eval('[data-ds=password-field]:not([data-disabled]):not([data-readonly])', (e) => e.setAttribute('data-qa', ''));
const T = '[data-qa] [data-part=toggle]';
const pv = () => p.evaluate(() => { const r = document.querySelector('[data-qa]'); const t = r.querySelector('[data-part=toggle]'); return `type=${r.querySelector('input').type} visible=${r.hasAttribute('data-visible')} pressed=${t.getAttribute('aria-pressed')} label=${t.getAttribute('aria-label')}`; });
await p.focus(T); await tick(); L('pw toggle', await pv(), await active());
await press('Enter'); L('Enter', await pv(), await active());
await press(' '); L('Space', await pv(), await active());
await p.click(T); await tick(); L('click', await pv(), await active());

await go('inline-edit');
const ies = await p.$$eval('[data-ds=inline-edit]', (x) => x.map((e) => `${e.getAttribute('data-state')} ${e.hasAttribute('data-disabled')}`));
L('inline roots', ies.join(' | '));
await p.$eval('[data-ds=inline-edit][data-state=viewing]:not([data-disabled])', (e) => e.setAttribute('data-qa', ''));
const st = () => p.evaluate(() => { const r = document.querySelector('[data-qa]'); const i = r.querySelector('input'); return `state=${r.getAttribute('data-state')} display=${r.querySelector('[data-part=display]')?.textContent.trim()} input=${i ? JSON.stringify(i.value) + ' sel=' + i.selectionStart + '-' + i.selectionEnd : '-'} status=${r.querySelector('[data-part=status]').textContent}`; });
await p.focus('[data-qa] [data-part=display]'); await tick(); L('display focus', await st(), await active());
await press('Enter'); L('Enter', await st(), await active());
await p.keyboard.type('Renamed'); await press('Enter'); L('Enter commit', await st(), await active());
await press(' '); L('Space', await st(), await active());
await p.keyboard.type('Dropped'); await press('Escape'); L('Escape', await st(), await active());
await p.click('[data-qa] [data-part=display]'); await tick(); L('click', await st(), await active());
await p.keyboard.type('Blur'); await p.click('body', { position: { x: 5, y: 5 } }); await tick(); L('click outside', await st(), await active());
console.log(log.join('\n'));
await b.close();
