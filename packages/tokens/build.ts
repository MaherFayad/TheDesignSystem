const MATERIALS = ['glass', 'glass-strong', 'glass-clear', 'glass-tinted', 'glass-flat', 'titlebar', 'menubar', 'dock'];

function renderCss(r: BuildResult, modes: Mode[]): string {
  const { prefix, base, densities } = r;
  const blocks: string[] = [];
  // Base tokens may alias style tokens; buildTokens checked those per mode.
  const scope: TokenMap = new Map([...base, ...r.modes.flatMap((m) => [...m.own])]);
  blocks.push(cssBlock(':root,\n  [data-style]', base, prefix, scope));
  for (const d of densities) blocks.push(cssBlock(`[data-density='${d.id}']`, d.tokens, prefix, scope));
  for (const m of modes) {
    const scheme = m.scheme === 'dark' || m.scheme === 'light' ? [`color-scheme: ${m.scheme};`] : [];
    blocks.push(cssBlock(`[data-style='${m.style}'][data-scheme='${m.scheme}']`, m.own, prefix, m.all, scheme));
  }

  // Reduced motion: every duration and delay goes to zero, except timing that
  // is not motion (hover intent), marked $extensions["ds.motion"]: false.
  const motion = sortedPaths(base).filter((p) => (p.startsWith('duration.') || p.startsWith('delay.')) && base.get(p)!.extensions?.['ds.motion'] !== false);
  if (motion.length) {
    const lines = motion.map((p) => `      ${cssVar(prefix, p)}: 0ms;`);
    blocks.push(`  @media (prefers-reduced-motion: reduce) {\n    :root,\n    [data-style] {\n${lines.join('\n')}\n    }\n  }`);
  }

  // Reduced transparency and more contrast: every material becomes the solid glass.
  const solid = `var(${cssVar(prefix, 'color.material.glass-solid')})`;
  const mats = solidMaterialPaths(modes);
  if (mats.length) {
    const lines = (indent: string) => mats.map((p) => `${indent}${cssVar(prefix, p)}: ${solid};`).join('\n');
    blocks.push(`  @media (prefers-reduced-transparency: reduce) {\n    [data-style][data-scheme] {\n${lines('      ')}\n    }\n  }`);
    blocks.push(`  @media (prefers-contrast: more) {\n    [data-style][data-scheme] {\n${lines('      ')}\n    }\n  }`);
    blocks.push(`  [data-style][data-scheme][data-contrast='more'] {\n${lines('    ')}\n  }`);
  }

  return [
    `/* ${HEADER} */`,
    '@layer ds.reset, ds.tokens, ds.base, ds.recipes, ds.overrides;',
    '',
    '@layer ds.tokens {',
    blocks.join('\n\n'),
    '}',
    '',
  ].join('\n');
}

function fluidMinimums(r: BuildResult): Record<string, number> {
  const out: Record<string, number> = {};
  for (const p of sortedPaths(r.base)) {
    const f = fluidOf(r.base.get(p)!);
    if (f) out[p] = f.min;
  }
  return out;
}

function solidMaterialPaths(modes: Mode[]): string[] {
  return MATERIALS.map((m) => `color.material.${m}`).filter((p) => modes.some((m) => m.all.has(p)));
}

function nativeTheme(mode: Mode): Record<string, unknown> {
  const obj: Record<string, unknown> = {};
  for (const path of sortedPaths(mode.all)) {
    const t = mode.all.get(path)!;
    setPath(obj, nativePath(t, mode.all), nativeValue(t, mode.all));
  }
  return obj;
}

function nativeThemeType(mode: Mode): Record<string, unknown> {
  const obj: Record<string, unknown> = {};
  for (const path of sortedPaths(mode.all)) {
    const t = mode.all.get(path)!;
    setPath(obj, nativePath(t, mode.all), nativeType(t, mode.all));
  }
  return obj;
}

const NATIVE_TYPES_DOC = `/**
 * One resolved theme: plain numbers and strings, no CSS.
 *
 * - Colours are hex, or rgba() when translucent.
 * - Dimensions are numbers in px (dp on Android, pt on iOS). rem is converted at 16px.
 * - Fluid values (space, font.size) use their max.
 * - em tokens (radius.control, font.tracking.*) are converted at 16px. For letter
 *   spacing at another size, scale by fontSize / 16.
 * - font.leading.* are multipliers, not line heights: lineHeight = fontSize * leading.
 * - font.family.* is the first real family name of the stack. CSS keywords such as
 *   system-ui or ui-monospace are skipped; undefined means the platform default font.
 * - Keys ending in -window-ratio come from vh or vw tokens: a ratio from 0 to 1 that
 *   you multiply by the window height (vh) or width (vw), for example from
 *   useWindowDimensions(). dialog.height.max-window-ratio is 0.8 for 80vh.
 * - Durations are milliseconds. Eases are cubic bezier control points.
 * - Shadows are React Native shadow props, from the outer layer with the largest blur.
 */`;

function render(r: BuildResult): Record<string, string> {
  const files: Record<string, string> = {};
  const { prefix, modes, base, densities } = r;
  const styles = [...new Set(modes.map((m) => m.style))];
  const schemes = [...new Set(modes.map((m) => m.scheme))].sort(compareNames);

  // 1. CSS
  files['css/tokens.css'] = renderCss(r, modes);
  for (const s of styles) files[`css/${s}.css`] = renderCss(r, modes.filter((m) => m.style === s));

  // 2. Native theme objects
  const themes = modes.map((m) => ({ mode: m, name: identifier(`${m.style} ${m.scheme}`), obj: nativeTheme(m) }));
  const first = themes[0];
  files['native/types.ts'] = [
    `// ${HEADER}`,
    '',
    NATIVE_TYPES_DOC,
    `export interface Theme ${first ? tsType(nativeThemeType(first.mode), '') : '{}'}`,
    '',
  ].join('\n');
  for (const t of themes) {
    files[`native/${t.mode.id}.ts`] = [
      `// ${HEADER}`,
      "import type { Theme } from './types';",
      '',
      `export const ${t.name}: Theme = ${tsLiteral(t.obj, '')};`,
      '',
    ].join('\n');
  }
  const densityObjs = densities.map((d) => {
    const obj: Record<string, unknown> = {};
    const scope = new Map([...base, ...d.tokens]);
    for (const p of sortedPaths(d.tokens)) setPath(obj, nativePath(d.tokens.get(p)!, scope), nativeValue(d.tokens.get(p)!, scope));
    return { id: d.id, obj };
  });
  const themeMap: Record<string, Record<string, string>> = {};
  for (const t of themes) (themeMap[t.mode.style] ??= {})[t.mode.scheme] = t.name;
  files['native/index.ts'] = [
    `// ${HEADER}`,
    ...themes.map((t) => `import { ${t.name} } from './${t.mode.id}';`),
    "import type { Theme } from './types';",
    '',
    'export type { Theme };',
    `export type StyleId = ${styles.map((s) => `'${s}'`).join(' | ') || 'never'};`,
    `export type Scheme = ${schemes.map((s) => `'${s}'`).join(' | ') || 'never'};`,
    `export type Density = 'default'${densities.map((d) => ` | '${d.id}'`).join('')};`,
    '',
    `export const themes: Record<StyleId, Partial<Record<Scheme, Theme>>> = {\n${Object.keys(themeMap)
      .sort(compareNames)
      .map((s) => `  ${tsKey(s)}: { ${Object.entries(themeMap[s]!).sort(([a], [b]) => compareNames(a, b)).map(([k, v]) => `${tsKey(k)}: ${v}`).join(', ')} },`)
      .join('\n')}\n};`,
    '',
    '/** Base token overrides per density. Merge over a theme; `default` has none. */',
    `export const densities = ${tsLiteral(Object.fromEntries(densityObjs.map((d) => [d.id, d.obj])), '')} as const;`,
    '',
    '/** The px size of 1em and 1rem in these themes. em tokens (radius.control, font.tracking.*) were converted with it. */',
    `export const emBase = ${ROOT_FONT_PX};`,
    '',
    '/** The minimum of every fluid token, in px, keyed by token path. Themes hold the maximum. */',
    `export const fluidMin: Readonly<Record<string, number>> = ${tsLiteral(fluidMinimums(r), '')};`,
    '',
    '/** Material token paths that become color.material.glass-solid under reduced transparency and more contrast. */',
    `export const solidMaterials: readonly string[] = [${solidMaterialPaths(modes).map((p) => `'${p}'`).join(', ')}];`,
    '',
  ].join('\n');

  // 3. Types
  const allNames = new Set<string>(base.keys());
  for (const m of modes) for (const p of m.own.keys()) allNames.add(p);
  const names = [...allNames].sort(compareNames);
  files['types/tokens.d.ts'] = [
    `// ${HEADER}`,
    '//',
    '// Breakpoints (breakpoint.*) are emitted as custom properties for scripts, but custom',
    '// properties do not work in media queries. Component CSS writes the literal and names the',
    '// token in a comment, for example @media (width < 48rem) /* breakpoint.tablet */. Tooling',
    '// that supports @custom-media can import dist/css/custom-media.css instead.',
    '',
    `export type TokenName =\n${names.map((n) => `  | '${n}'`).join('\n')};`,
    '',
    `export type CssVariable =\n${names.map((n) => `  | '${cssVar(prefix, n)}'`).join('\n')};`,
    '',
    `export type StyleId = ${styles.map((s) => `'${s}'`).join(' | ') || 'never'};`,
    `export type Scheme = ${schemes.map((s) => `'${s}'`).join(' | ') || 'never'};`,
    `export type Density = 'default'${densities.map((d) => ` | '${d.id}'`).join('')};`,
    '',
  ].join('\n');

  // 4. Figma: one flat file per mode.
  for (const m of modes) {
    const variables: Record<string, FigmaVariable> = {};
    for (const p of sortedPaths(m.all)) variables[p.replace(/\./g, '/')] = figmaVariable(m.all.get(p)!, m.all, prefix);
    files[`figma/${m.id}.json`] = JSON.stringify({ mode: m.id, style: m.style, scheme: m.scheme, variables }, null, 2) + '\n';
  }

  // 5. Tailwind v4 bridge: theme keys point at the system variables.
  const tw: string[] = [];
  for (const n of names) {
    const hit = TAILWIND.find(([p]) => n.startsWith(p));
    if (!hit) continue;
    tw.push(`  --${hit[1]}-${n.slice(hit[0].length).replace(/\./g, '-')}: var(${cssVar(prefix, n)});`);
  }
  // Breakpoints feed media queries, where var() does not work: literal values.
  for (const p of sortedPaths(base).filter((x) => x.startsWith('breakpoint.'))) {
    const t = base.get(p)!;
    tw.push(`  --breakpoint-${p.slice('breakpoint.'.length).replace(/\./g, '-')}: ${cssValue(t, t.value, prefix, base)};`);
  }
  files['tailwind/theme.css'] = [`/* ${HEADER} */`, '@theme inline {', ...tw, '}', ''].join('\n');

  // 6. Custom media for the breakpoints, for tooling that supports @custom-media.
  const bps = sortedPaths(base).filter((x) => x.startsWith('breakpoint.'));
  if (bps.length) {
    const lines = bps.flatMap((p) => {
      const t = base.get(p)!;
      const v = cssValue(t, t.value, prefix, base);
      const name = p.slice('breakpoint.'.length).replace(/\./g, '-');
      return [`@custom-media --${prefix}-below-${name} (width < ${v});`, `@custom-media --${prefix}-${name}-up (width >= ${v});`];
    });
    files['css/custom-media.css'] = [
      `/* ${HEADER} */`,
      '/* Breakpoints as @custom-media, for tooling that supports it. Custom properties do not work',
      '   in media queries: plain component CSS writes the literal with a comment naming the token,',
      '   for example @media (width < 48rem) { ... } with a breakpoint.tablet comment. */',
      ...lines,
      '',
    ].join('\n');
  }

  return files;
}

/** Writes the result to `dist`, replacing what was there. */
export function writeTokens(result: BuildResult, outDir: string): void {
  rmSync(outDir, { recursive: true, force: true });
  for (const [rel, content] of Object.entries(result.files).sort(([a], [b]) => compareNames(a, b))) {
    const p = join(outDir, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
  }
}

