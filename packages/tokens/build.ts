const HEADER = 'Generated by packages/tokens/build.ts. Do not edit.';
const ALIAS = /^\{([^{}]+)\}$/;
const ROOT_FONT_PX = 16;

/** Natural order: `2xl` after `xl`, `10` after `9`. Locale free, so stable. */
export function compareNames(a: string, b: string): number {
  const ax = a.split(/(\d+)/);
  const bx = b.split(/(\d+)/);
  for (let i = 0; i < Math.max(ax.length, bx.length); i++) {
    const x = ax[i] ?? '';
    const y = bx[i] ?? '';
    if (x === y) continue;
    const nx = /^\d+$/.test(x);
    const ny = /^\d+$/.test(y);
    if (nx && ny) return Number(x) - Number(y);
    return x < y ? -1 : 1;
  }
  return 0;
}

function sortedPaths(map: TokenMap): string[] {
  return [...map.keys()].sort(compareNames);
}

function num(n: number, digits = 4): string {
  const f = 10 ** digits;
  const r = Math.round(n * f) / f;
  return Object.is(r, -0) ? '0' : String(r);
}

function readJson(path: string): unknown {
  return JSON.parse(readFileSync(path, 'utf8')) as unknown;
}

function isObject(x: unknown): x is Record<string, unknown> {
  return typeof x === 'object' && x !== null && !Array.isArray(x);
}

/** Flattens a DTCG tree. Group `$type` is inherited by the tokens under it. */
export function flatten(tree: unknown, file: string, out: TokenMap = new Map(), prefix: string[] = [], inherited?: string): TokenMap {
  if (!isObject(tree)) return out;
  const groupType = typeof tree.$type === 'string' ? tree.$type : inherited;
  for (const [key, node] of Object.entries(tree)) {
    if (key.startsWith('$')) continue;
    if (/[{}.]/.test(key)) throw new Error(`${file}: invalid token name "${key}"`);
    if (!isObject(node)) throw new Error(`${file}: ${[...prefix, key].join('.')} is not an object`);
    const path = [...prefix, key];
    if ('$value' in node) {
      const type = typeof node.$type === 'string' ? node.$type : groupType;
      if (!type) throw new Error(`${file}: ${path.join('.')} has no $type`);
      const token: Token = { path: path.join('.'), type, value: node.$value };
      if (typeof node.$description === 'string') token.description = node.$description;
      if (isObject(node.$extensions)) token.extensions = node.$extensions;
      if (out.has(token.path)) throw new Error(`${file}: ${token.path} defined twice`);
      out.set(token.path, token);
    } else {
      flatten(node, file, out, path, groupType);
    }
  }
  return out;
}

function aliasTarget(value: unknown): string | undefined {
  return typeof value === 'string' ? ALIAS.exec(value)?.[1] : undefined;
}

/** Resolves aliases, including aliases inside composite values. */
export function resolveValue(value: unknown, map: TokenMap, where: string, seen: string[] = []): unknown {
  const target = aliasTarget(value);
  if (target) {
    if (seen.includes(target)) throw new Error(`${where}: circular alias ${[...seen, target].join(' -> ')}`);
    const t = map.get(target);
    if (!t) throw new Error(`${where}: alias {${target}} does not resolve`);
    return resolveValue(t.value, map, where, [...seen, target]);
  }
  if (Array.isArray(value)) return value.map((v) => resolveValue(v, map, where, seen));
  if (isObject(value) && !('colorSpace' in value)) {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value)) out[k] = resolveValue(v, map, where, seen);
    return out;
  }
  return value;
}

/** The token a chain of aliases ends at, so its type and extensions apply. */
function finalToken(token: Token, map: TokenMap): Token {
  let t = token;
  const seen = new Set<string>();
  for (let target = aliasTarget(t.value); target; target = aliasTarget(t.value)) {
    if (seen.has(target)) throw new Error(`${token.path}: circular alias`);
    seen.add(target);
    const next = map.get(target);
    if (!next) throw new Error(`${token.path}: alias {${target}} does not resolve`);
    t = next;
  }
  return t;
}

function fluidOf(token: Token): Fluid | undefined {
  const f = token.extensions?.['ds.fluid'];
  return isObject(f) ? (f as unknown as Fluid) : undefined;
}

function unitOf(token: Token): string | undefined {
  const u = token.extensions?.['ds.unit'];
  return typeof u === 'string' ? u : undefined;
}

function rgbOf(c: ColorValue): [number, number, number, number] {
  const alpha = c.alpha ?? 1;
  if (c.hex && /^#[0-9a-f]{6}$/i.test(c.hex)) {
    const h = c.hex.slice(1);
    return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16), alpha];
  }
  if (c.colorSpace !== 'srgb') throw new Error(`colour space ${c.colorSpace} needs a hex fallback`);
  const [r, g, b] = c.components.map((x) => (x === 'none' ? 0 : Math.round(x * 255)));
  return [r ?? 0, g ?? 0, b ?? 0, alpha];
}

function hexOf(r: number, g: number, b: number): string {
  return '#' + [r, g, b].map((x) => x.toString(16).padStart(2, '0')).join('');
}

function px(d: Dimension): number {
  if (d.unit === 'px') return d.value;
  if (d.unit === 'rem') return d.value * ROOT_FONT_PX;
  throw new Error(`unknown dimension unit ${d.unit}`);
}

function ms(d: Dimension): number {
  if (d.unit === 'ms') return d.value;
  if (d.unit === 's') return d.value * 1000;
  throw new Error(`unknown duration unit ${d.unit}`);
}

const GENERIC_FONTS = new Set([
  'serif', 'sans-serif', 'monospace', 'cursive', 'fantasy', 'system-ui', 'ui-serif', 'ui-sans-serif',
  'ui-monospace', 'ui-rounded', 'emoji', 'math', 'fangsong', '-apple-system', 'BlinkMacSystemFont',
]);

// ---------------------------------------------------------------- CSS values

export function cssVar(prefix: string, path: string): string {
  return `--${prefix}-${path.replace(/\./g, '-')}`;
}

function cssColor(c: ColorValue): string {
  const [r, g, b, a] = rgbOf(c);
  return a >= 1 ? hexOf(r, g, b) : `rgb(${r} ${g} ${b} / ${num(a)})`;
}

function cssClamp(f: Fluid): string {
  if (f.min === f.max) return `${num(f.max)}px`;
  const slope = (f.max - f.min) / (f.maxViewport - f.minViewport);
  const intercept = f.min - slope * f.minViewport;
  return `clamp(${num(f.min)}px, calc(${num(intercept, 3)}px + ${num(slope * 100, 3)}vw), ${num(f.max)}px)`;
}

/** A CSS value. Aliases become var() so density and scheme changes flow through. */
function cssValue(token: Token, value: unknown, prefix: string, map: TokenMap): string {
  const target = aliasTarget(value);
  if (target) {
    if (!map.has(target)) throw new Error(`${token.path}: alias {${target}} does not resolve`);
    return `var(${cssVar(prefix, target)})`;
  }
  const part = (v: unknown, type: string): string => cssValue({ path: token.path, type, value: v }, v, prefix, map);
  switch (token.type) {
    case 'color':
      return cssColor(value as ColorValue);
    case 'dimension': {
      const fluid = fluidOf(token);
      if (fluid) return cssClamp(fluid);
      const d = value as Dimension;
      return `${num(d.value)}${d.unit}`;
    }
    case 'duration': {
      const d = value as Dimension;
      return `${num(d.value)}${d.unit}`;
    }
    case 'number': {
      const unit = unitOf(token);
      return `${num(value as number)}${unit ?? ''}`;
    }
    case 'fontWeight':
      return String(value);
    case 'cubicBezier':
      return `cubic-bezier(${(value as number[]).map((n) => num(n)).join(', ')})`;
    case 'fontFamily': {
      const list = Array.isArray(value) ? (value as string[]) : [value as string];
      return list.map((f) => (GENERIC_FONTS.has(f) ? f : `"${f}"`)).join(', ');
    }
    case 'shadow': {
      const layers = Array.isArray(value) ? value : [value];
      return layers
        .map((l) => {
          const s = l as ShadowLayer;
          const dims = [s.offsetX, s.offsetY, s.blur, s.spread].map((d) => part(d, 'dimension'));
          return [s.inset ? 'inset' : '', ...dims, part(s.color, 'color')].filter(Boolean).join(' ');
        })
        .join(', ');
    }
    case 'string':
      return String(value);
    default:
      throw new Error(`${token.path}: no CSS output for $type ${token.type}`);
  }
}

/** Viewport units with a dynamic form (dvh, dvw) for browsers that have it. */
const DYNAMIC_UNITS: Record<string, string> = { vh: 'dvh', vw: 'dvw' };

function cssBlock(selector: string, map: TokenMap, prefix: string, scope: TokenMap, extra: string[] = [], indent = '  '): string {
  const lines = [...extra];
  const dynamic: string[] = [];
  for (const path of sortedPaths(map)) {
    const t = map.get(path)!;
    lines.push(`${cssVar(prefix, path)}: ${cssValue(t, t.value, prefix, scope)};`);
    const unit = t.type === 'number' ? unitOf(t) : undefined;
    if (unit && unit in DYNAMIC_UNITS && typeof t.value === 'number') {
      dynamic.push(`${cssVar(prefix, path)}: ${num(t.value)}${DYNAMIC_UNITS[unit]};`);
    }
  }
  const block = (sel: string, ls: string[], ind: string) => `${ind}${sel} {\n${ls.map((l) => `${ind}  ${l}`).join('\n')}\n${ind}}`;
  const out = [block(selector, lines, indent)];
  // The static unit stays as the fallback; the dynamic form wins where supported.
  if (dynamic.length) {
    const inner = selector.replace(/\n/g, `\n  `);
    out.push(`${indent}@supports (height: 1dvh) {\n${block(inner, dynamic, `${indent}  `)}\n${indent}}`);
  }
  return out.join('\n\n');
}

// ---------------------------------------------------------------- native values

type NativeValue = string | number | number[] | Record<string, unknown> | undefined;

/** Units relative to the window. Native gets a ratio under a renamed key. */
const WINDOW_UNITS: Record<string, string> = { vh: 'height', vw: 'width' };

function windowUnit(token: Token, map: TokenMap): string | undefined {
  const t = finalToken(token, map);
  const unit = t.type === 'number' ? unitOf(t) : undefined;
  return unit && unit in WINDOW_UNITS ? unit : undefined;
}

/** The native key path: a window relative token gets `-window-ratio` on its last name. */
function nativePath(token: Token, map: TokenMap): string {
  return windowUnit(token, map) ? `${token.path}-window-ratio` : token.path;
}

/** The first real family name, or undefined for the platform default. */
function nativeFamily(value: unknown): string | undefined {
  const list = Array.isArray(value) ? (value as string[]) : [value as string];
  return list.find((f) => !GENERIC_FONTS.has(f));
}

function nativeColor(c: ColorValue): string {
  const [r, g, b, a] = rgbOf(c);
  return a >= 1 ? hexOf(r, g, b) : `rgba(${r}, ${g}, ${b}, ${num(a)})`;
}

/** React Native shadow props from the outer shadow with the largest blur. */
function nativeShadow(value: unknown): Record<string, unknown> {
  const layers = (Array.isArray(value) ? value : [value]) as ShadowLayer[];
  const outer = layers.filter((l) => !l.inset);
  const pick = outer.reduce<ShadowLayer | undefined>((best, l) => (!best || px(l.blur as Dimension) > px(best.blur as Dimension) ? l : best), undefined);
  if (!pick) {
    return { shadowColor: '#000000', shadowOffset: { width: 0, height: 0 }, shadowOpacity: 0, shadowRadius: 0, elevation: 0 };
  }
  const [r, g, b, a] = rgbOf(pick.color as ColorValue);
  const blur = px(pick.blur as Dimension);
  return {
    shadowColor: hexOf(r, g, b),
    shadowOffset: { width: px(pick.offsetX as Dimension), height: px(pick.offsetY as Dimension) },
    shadowOpacity: Number(num(a)),
    shadowRadius: Number(num(blur / 2)),
    elevation: a === 0 ? 0 : Math.min(24, Math.round(blur / 3)),
  };
}

function nativeValue(token: Token, map: TokenMap): NativeValue {
  const t = finalToken(token, map);
  const value = resolveValue(token.value, map, token.path);
  switch (t.type) {
    case 'color':
      return nativeColor(value as ColorValue);
    case 'dimension':
      return Number(num(px(value as Dimension)));
    case 'duration':
      return Number(num(ms(value as Dimension)));
    case 'number': {
      const unit = unitOf(t);
      const n = value as number;
      if (unit === 'em') return Number(num(n * ROOT_FONT_PX));
      if (unit && unit in WINDOW_UNITS) return Number(num(n / 100));
      if (unit === '%') return `${num(n)}%`;
      return n;
    }
    case 'fontWeight':
      return value as number;
    case 'cubicBezier':
      return value as number[];
    case 'fontFamily':
      return nativeFamily(value);
    case 'shadow':
      return nativeShadow(value);
    default:
      return String(value);
  }
}

const NATIVE_SHADOW_TYPE = `{
  readonly shadowColor: string;
  readonly shadowOffset: { readonly width: number; readonly height: number };
  readonly shadowOpacity: number;
  readonly shadowRadius: number;
  readonly elevation: number;
}`;

/** The TypeScript type of a native value, from the token type (not the value). */
function nativeType(token: Token, map: TokenMap): string {
  const t = finalToken(token, map);
  switch (t.type) {
    case 'color':
      return 'string';
    case 'number':
      return unitOf(t) === '%' ? 'string' : 'number';
    case 'cubicBezier':
      return 'readonly [number, number, number, number]';
    case 'fontFamily':
      return 'string | undefined';
    case 'shadow':
      return NATIVE_SHADOW_TYPE;
    case 'dimension':
    case 'duration':
    case 'fontWeight':
      return 'number';
    default:
      return 'string';
  }
}

function setPath(obj: Record<string, unknown>, path: string, value: unknown): void {
  const parts = path.split('.');
  let node = obj;
  for (const p of parts.slice(0, -1)) {
    node[p] ??= {};
    node = node[p] as Record<string, unknown>;
  }
  node[parts[parts.length - 1]!] = value;
}

function tsKey(k: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`;
}

function tsLiteral(value: unknown, indent: string): string {
  if (value === undefined) return 'undefined';
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  if (typeof value === 'number') return String(value);
  if (Array.isArray(value)) return `[${value.map((v) => tsLiteral(v, indent)).join(', ')}]`;
  const obj = value as Record<string, unknown>;
  const keys = Object.keys(obj).sort(compareNames);
  const inner = keys.map((k) => `${indent}  ${tsKey(k)}: ${tsLiteral(obj[k], `${indent}  `)},`);
  return `{\n${inner.join('\n')}\n${indent}}`;
}

/** Prints a tree whose leaves are type strings. */
function tsType(value: unknown, indent: string): string {
  if (typeof value === 'string') return value.replace(/\n/g, `\n${indent}`);
  const obj = value as Record<string, unknown>;
  const keys = Object.keys(obj).sort(compareNames);
  const inner = keys.map((k) => `${indent}  readonly ${tsKey(k)}: ${tsType(obj[k], `${indent}  `)};`);
  return `{\n${inner.join('\n')}\n${indent}}`;
}

function identifier(id: string): string {
  return id
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w, i) => (i === 0 ? w.toLowerCase() : w[0]!.toUpperCase() + w.slice(1).toLowerCase()))
    .join('');
}

// ---------------------------------------------------------------- figma values

interface FigmaVariable {
  type: 'COLOR' | 'FLOAT' | 'STRING';
  value: unknown;
  alias?: string;
  description?: string;
}

function figmaVariable(token: Token, map: TokenMap, prefix: string): FigmaVariable {
  const t = finalToken(token, map);
  const native = nativeValue(token, map);
  let v: FigmaVariable;
  if (t.type === 'color') {
    const [r, g, b, a] = rgbOf(resolveValue(token.value, map, token.path) as ColorValue);
    v = { type: 'COLOR', value: { r: Number(num(r / 255)), g: Number(num(g / 255)), b: Number(num(b / 255)), a: Number(num(a)) } };
  } else if (windowUnit(token, map) || t.type === 'fontFamily') {
    const resolved = resolveValue(token.value, map, token.path);
    const family = t.type === 'fontFamily' ? (Array.isArray(resolved) ? (resolved as string[]) : [resolved as string]) : [];
    v = { type: 'STRING', value: t.type === 'fontFamily' ? (nativeFamily(resolved) ?? family[0] ?? '') : cssValue(t, resolved, prefix, map) };
  } else if (typeof native === 'number') {
    v = { type: 'FLOAT', value: native };
  } else if (typeof native === 'string' && t.type !== 'shadow') {
    v = { type: 'STRING', value: native };
  } else {
    v = { type: 'STRING', value: cssValue(t, resolveValue(token.value, map, token.path), prefix, map) };
  }
  const target = aliasTarget(token.value);
  if (target) v.alias = target.replace(/\./g, '/');
  if (token.description) v.description = token.description;
  return v;
}

