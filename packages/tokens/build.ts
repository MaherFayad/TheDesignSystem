// The token build. Reads DTCG source files and writes five outputs to
// packages/tokens/dist: layered CSS, React Native theme objects, TypeScript
// token name types, flat Figma JSON per mode and a Tailwind v4 @theme bridge.
//
// Sources:
//   packages/tokens/src/base/*.json         tokens shared by every style
//   packages/tokens/src/density/<id>.json   overrides for [data-density='<id>']
//   packages/tokens/src/contract.json       semantic names every style fills
//   packages/styles/<id>/tokens.<scheme>.json   one style, one scheme
//
// Styles are discovered from the folders, so a new style needs no change here.
// The output is deterministic: sorted, no timestamps.
//
// Run: npx tsx packages/tokens/build.ts
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// ---------------------------------------------------------------- types

export interface Token {
  path: string;
  type: string;
  value: unknown;
  description?: string;
  extensions?: Record<string, unknown>;
}

export type TokenMap = Map<string, Token>;

export interface Mode {
  /** `<style>.<scheme>`, for example `studio.dark`. */
  id: string;
  style: string;
  scheme: string;
  /** Tokens from the style file only. */
  own: TokenMap;
  /** Base tokens plus the style tokens, which win. */
  all: TokenMap;
}

export interface ContractGroup {
  group: string;
  type: string;
  names: string[];
  added: string[];
}

export interface BuildResult {
  prefix: string;
  base: TokenMap;
  densities: { id: string; tokens: TokenMap }[];
  modes: Mode[];
  contract: ContractGroup[];
  /** Output files, keyed by path relative to `dist/`. */
  files: Record<string, string>;
}

interface ColorValue {
  colorSpace: string;
  components: (number | 'none')[];
  alpha?: number;
  hex?: string;
}

interface Dimension {
  value: number;
  unit: string;
}

interface ShadowLayer {
  color: ColorValue | string;
  offsetX: Dimension | string;
  offsetY: Dimension | string;
  blur: Dimension | string;
  spread: Dimension | string;
  inset?: boolean;
}

interface Fluid {
  min: number;
  max: number;
  minViewport: number;
  maxViewport: number;
}

