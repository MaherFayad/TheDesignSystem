// Gallery screen list for React Native.
{
  const comps = join(root, 'packages/native/src/components');
  const app = join(root, 'apps/gallery-native/src');
  if (existsSync(app)) {
    const imports: string[] = [];
    const rows: string[] = [];
    for (const name of dirs(comps)) {
      if (!existsSync(join(comps, name, `${name}.demo.tsx`))) continue;
      imports.push(`import ${name}Demo from '../../../packages/native/src/components/${name}/${name}.demo';`);
      rows.push(`  { name: '${name}', Demo: ${name}Demo },`);
    }
    write(
      join(app, 'screens.gen.ts'),
      header +
        `import type { ComponentType } from 'react';\n${imports.join('\n')}\n\n` +
        `export const screens: { name: string; Demo: ComponentType }[] = [\n${rows.join('\n')}\n];\n`,
    );
  }
}
