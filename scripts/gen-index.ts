// Writes every barrel and route list from the folders that exist.
// Subagents never edit the files this script writes.
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = join(import.meta.dirname, '..');
const header = '// Generated by scripts/gen-index.ts. Do not edit.\n';

function dirs(path: string): string[] {
  if (!existsSync(path)) return [];
  return readdirSync(path)
    .filter((n) => statSync(join(path, n)).isDirectory())
    .sort((a, b) => a.localeCompare(b, 'en'));
}

function files(path: string, ext: string): string[] {
  if (!existsSync(path)) return [];
  return readdirSync(path)
    .filter((n) => n.endsWith(ext))
    .sort((a, b) => a.localeCompare(b, 'en'));
}

function write(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  if (existsSync(path) && readFileSync(path, 'utf8') === content) return;
  writeFileSync(path, content);
  console.log(`wrote ${path.slice(root.length + 1)}`);
}

// TypeScript barrels for the component packages.
function barrel(pkg: string, extra: string[]): void {
  const src = join(root, 'packages', pkg, 'src');
  if (!existsSync(src)) return;
  const lines: string[] = [];
  for (const folder of extra) {
    if (existsSync(join(src, folder, 'index.ts'))) lines.push(`export * from './${folder}/index';`);
  }
  for (const name of dirs(join(src, 'components'))) {
    if (existsSync(join(src, 'components', name, 'index.ts'))) {
      lines.push(`export * from './components/${name}/index';`);
    }
  }
  if (lines.length === 0) lines.push('export {};');
  write(join(src, 'index.ts'), header + lines.join('\n') + '\n');
}

for (const pkg of ['react', 'native', 'charts-react', 'charts-native', 'ai-react', 'ai-native']) {
  barrel(pkg, ['theme']);
}
for (const pkg of ['angular', 'charts-angular', 'ai-angular']) {
  barrel(pkg, ['theme', 'behavior']);
}

// Barrels for the pure TypeScript packages: one export per top level module.
for (const pkg of ['shared', 'motion']) {
  const src = join(root, 'packages', pkg, 'src');
  if (!existsSync(src)) continue;
  const lines: string[] = [];
  for (const f of files(src, '.ts')) {
    if (f === 'index.ts' || f.endsWith('.test.ts') || f.endsWith('.d.ts')) continue;
    lines.push(`export * from './${f.slice(0, -3)}';`);
  }
  for (const d of dirs(src)) {
    if (existsSync(join(src, d, 'index.ts'))) lines.push(`export * from './${d}/index';`);
  }
  if (lines.length === 0) lines.push('export {};');
  write(join(src, 'index.ts'), header + lines.sort().join('\n') + '\n');
}

// Style registry: every style.json, for Theme providers and the CLI.
{
  const stylesRoot = join(root, 'packages/styles');
  const ids = dirs(stylesRoot).filter((id) => existsSync(join(stylesRoot, id, 'style.json')));
  const imports = ids.map((id) => `import ${id} from './${id}/style.json' with { type: 'json' };`);
  write(
    join(stylesRoot, 'registry.gen.ts'),
    header + imports.join('\n') + `\n\nexport const styles = { ${ids.join(', ')} } as const;\nexport type StyleId = keyof typeof styles;\n`,
  );
}

// CSS barrel: layer order first, then reset, base and one file per component.
{
  const src = join(root, 'packages/css/src');
  const lines = ['@layer ds.reset, ds.tokens, ds.base, ds.recipes, ds.overrides;'];
  for (const f of ['reset.css', 'base.css']) {
    if (existsSync(join(src, f))) lines.push(`@import './${f}';`);
  }
  for (const f of files(join(src, 'components'), '.css')) lines.push(`@import './components/${f}';`);
  write(join(src, 'index.css'), '/* Generated by scripts/gen-index.ts. Do not edit. */\n' + lines.join('\n') + '\n');
}

// One recipes barrel per style pack, and one for all of them.
{
  const stylesRoot = join(root, 'packages/styles');
  const all: string[] = [];
  for (const id of dirs(stylesRoot)) {
    const recipes = files(join(stylesRoot, id, 'recipes'), '.css');
    if (!existsSync(join(stylesRoot, id, 'style.json'))) continue;
    const lines = recipes.map((f) => `@import './recipes/${f}';`);
    if (existsSync(join(stylesRoot, id, 'fonts.css'))) lines.unshift(`@import './fonts.css';`);
    write(join(stylesRoot, id, 'index.css'), '/* Generated by scripts/gen-index.ts. Do not edit. */\n' + lines.join('\n') + '\n');
    all.push(`@import './${id}/index.css';`);
  }
  write(join(stylesRoot, 'index.css'), '/* Generated by scripts/gen-index.ts. Do not edit. */\n' + all.join('\n') + '\n');
}

// One JSON file with every manifest, for docs, contract tests, CLI and MCP.
{
  const src = join(root, 'packages/manifest/src');
  const out: unknown[] = [];
  for (const kind of dirs(src)) {
    for (const f of files(join(src, kind), '.manifest.json')) {
      out.push(JSON.parse(readFileSync(join(src, kind, f), 'utf8')));
    }
  }
  write(join(root, 'packages/manifest/manifests.gen.json'), JSON.stringify(out, null, 2) + '\n');
}

// Gallery route list for React: one lazy demo per component folder.
{
  const comps = join(root, 'packages/react/src/components');
  const app = join(root, 'apps/gallery-react/src');
  if (existsSync(app)) {
    const rows: string[] = [];
    for (const name of dirs(comps)) {
      if (!existsSync(join(comps, name, `${name}.demo.tsx`))) continue;
      const slug = name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
      rows.push(
        `  { name: '${name}', slug: '${slug}', load: () => import('../../../packages/react/src/components/${name}/${name}.demo') },`,
      );
    }
    write(
      join(app, 'routes.gen.ts'),
      header +
        `import type { ComponentType } from 'react';\n\n` +
        `export interface DemoRoute {\n  name: string;\n  slug: string;\n  load: () => Promise<{ default: ComponentType }>;\n}\n\n` +
        `export const routes: DemoRoute[] = [\n${rows.join('\n')}\n];\n`,
    );
  }
}

