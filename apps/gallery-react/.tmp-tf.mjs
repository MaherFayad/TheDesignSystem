import { chromium } from 'playwright';
const [base] = process.argv.slice(2);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
await p.addInitScript(() => { const o = Element.prototype.animate; window.__log = []; Element.prototype.animate = function (k, opts) { window.__log.push(`${opts?.id} ${this.tagName} ${this.getAttribute('data-part')} ${this.textContent?.slice(0,20)}`); return o.call(this, k, opts); }; });
await p.goto(`${base}/interactions?focus=collection-flip`);
await p.waitForSelector('[data-interaction-stage]', { state: 'attached' });
await p.waitForTimeout(1200);
await p.evaluate(() => (window.__log = []));
const input = p.locator('[data-interaction-stage] [data-ds=tag-field] input[data-part=control]');
await input.fill('Brand');
console.log('after fill', await p.evaluate(() => window.__log.splice(0)));
await p.keyboard.press('Enter');
await p.waitForTimeout(100);
console.log('after enter', await p.evaluate(() => window.__log.splice(0)));
await p.locator('[data-interaction-stage] [data-part=tag-remove]').first().click();
await p.waitForTimeout(100);
console.log('after remove', await p.evaluate(() => window.__log.splice(0)));
console.log(await p.locator('[data-interaction-stage] [data-ds=tag-field]').evaluate((e) => e.outerHTML.slice(0, 300)));
await b.close();
